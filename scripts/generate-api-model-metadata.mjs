#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";

// Same normalisation as modelKey in apps/copilot-api/model_metadata.go: a
// pricing tier suffix such as "(Default)" is not a different model.
const pricingSuffix =
  /\s*\((default(?:, [^()]*)?|long context, [^()]*|fast mode|preview)\)$/i;
export function modelKey(name) {
  let key = name.trim();
  for (
    let next = key.replace(pricingSuffix, "");
    next !== key;
    next = key.replace(pricingSuffix, "")
  )
    key = next;
  return key.replaceAll(" ", "-").toLowerCase();
}

// GitHub drops models from its pricing page, but usage history still names
// them. Carry every model the previous file knew and the page no longer lists
// into `retired`, so copilot-api keeps classifying it without a hand edit.
export function retiredModels(previous, models) {
  const current = new Set(models.map((m) => modelKey(m.model)));
  return [
    ...new Map(
      [...(previous.retired ?? []), ...(previous.models ?? [])]
        .filter((m) => !current.has(modelKey(m.model)))
        .map(({ model, provider, category }) => [
          model,
          { model, provider, category },
        ]),
    ).values(),
  ].sort((a, b) => (a.model < b.model ? -1 : a.model > b.model ? 1 : 0));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();

async function main() {
  const source = "apps/my-copilot/src/lib/model-pricing.ts";
  const code = stripTypeScriptTypes(
    readFileSync(new URL(`../${source}`, import.meta.url), "utf8"),
  );
  const { MODEL_PRICING, PRICING_SOURCE_URL, PRICING_LAST_UPDATED } =
    await import(
      `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`
    );
  const target = new URL(
    "../apps/copilot-api/model_metadata.json",
    import.meta.url,
  );
  const models = MODEL_PRICING.map(({ model, provider, category }) => ({
    model,
    provider,
    category,
  }));
  let previous = { models: [], retired: [] };
  try {
    previous = JSON.parse(readFileSync(target, "utf8"));
  } catch (error) {
    // Without the previous file every retired model is lost; demand intent.
    if (error.code !== "ENOENT" || !process.argv.includes("--init"))
      throw error;
  }
  const retired = retiredModels(previous, models);
  const metadata = {
    _generated:
      "Generated by scripts/generate-api-model-metadata.mjs; do not edit manually.",
    source,
    source_url: PRICING_SOURCE_URL,
    updated: PRICING_LAST_UPDATED,
    models,
    retired,
  };
  const output = `${JSON.stringify(metadata, null, 2)}\n`;
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) {
      throw new Error(
        "API model metadata is stale; run node scripts/generate-api-model-metadata.mjs",
      );
    }
  } else {
    writeFileSync(target, output);
  }
}
