// setupAnswers holds the answers collected by the first-run config wizard.
// Model and ReasoningEffort are empty string when the user chose to leave them unset.
type setupAnswers struct {
	Client          string
	Model           string // empty = don't write the key
	Mode            string
	ReasoningEffort string // empty = don't write the key
	AutoUpdate      string // "true" or "false"
	Autonomy        string // empty = not asked (not Copilot): leave the key
}

// writeSetupConfig writes the wizard's answers. An existing config that
// parses is edited in place, key by key, and only where an answer differs
// from what the file holds: comments, order and every key the wizard does not
// ask about stay as they are, and Enter on every question leaves the file
// byte for byte (#1348). Otherwise it writes a new file, using the existing
// formatTOMLValue helpers so the output is consistent with 'config set'.
// The config is validated before writing; an error is returned if it is invalid.
func writeSetupConfig(answers setupAnswers) error {
	if answers.Client == "" {
		answers.Client = "copilot"
	}
	if answers.Mode == "" {
		answers.Mode = "default"
	}
	if data, err := os.ReadFile(configPath()); err == nil {
		if file, ok := decodesTo(string(data)); ok {
			return mergeSetupAnswers(file, answers)
		}
	}

	var lines []string
	lines = append(lines,
		"# nav-pilot configuration",
		"# Generated by: nav-pilot config setup",
		"# Edit directly or run 'nav-pilot config set <key> <value>' to change.",
		"",
		"# Configuration schema version. Must be 1.",
		"version = 1",
		"",
	)

	// Preserve a persisted agentpakke source: the wizard does not ask about it,
	// and rewriting the file must not silently drop the user's selection (B2).
	if existing, err := readConfig(); err == nil && existing != nil && existing.Source != nil {
		if persisted := strings.TrimSpace(*existing.Source); persisted != "" {
			sourceVal, _ := formatTOMLValue(findKeyDef("source"), persisted)
			lines = append(lines, "source = "+sourceVal)
		}
	}

	// The client is always written: a later change of the built-in default
	// must not move a user who answered this (#1029). For the rest only what
	// differs from the default is written, so a later default reaches them.
	clientVal, _ := formatTOMLValue(findKeyDef("client"), answers.Client)
	lines = append(lines, "client = "+clientVal)
	if answers.Mode != findKeyDef("mode").defaultVal {
		modeVal, _ := formatTOMLValue(findKeyDef("mode"), answers.Mode)
		lines = append(lines, "mode = "+modeVal)
	}

	// Written whenever it was asked, with the mark that the user chose it
	// (autonomyChosenConservative). Only the Copilot CLI reads it, so for
	// the others it is not asked and not written.
	if answers.Autonomy != "" {
		lines = append(lines, "autonomy = "+tomlString(answers.Autonomy), "autonomy_chosen = true")
	}

	if answers.Model != "" {
		modelVal, _ := formatTOMLValue(findKeyDef("model"), answers.Model)
		lines = append(lines, "model = "+modelVal)
	}
	if answers.ReasoningEffort != "" {
		effortVal, _ := formatTOMLValue(findKeyDef("reasoning_effort"), answers.ReasoningEffort)
		lines = append(lines, "reasoning_effort = "+effortVal)
	}

	if answers.AutoUpdate != "" && answers.AutoUpdate != findKeyDef("auto_update").defaultVal {
		lines = append(lines, "auto_update = "+answers.AutoUpdate)
	}

	content := strings.Join(lines, "\n") + "\n"

	// Validate before writing.
	var cfg Config
	if _, err := toml.Decode(content, &cfg); err != nil {
		return fmt.Errorf("internal error building config TOML: %w", err)
	}
	if err := validateConfig(&cfg); err != nil {
		return fmt.Errorf("internal error: generated config is invalid: %w", err)
	}

	return writeConfigFile(configPath(), []byte(content), nil)
}

// mergeSetupAnswers edits the keys whose answer differs from file, the parsed
// config. The rules are the new file's: client is written when asked, the
// rest is removed when the answer is its default or unset. A missing client
// means what a launch resolves it to (copilot for a config from before it),
// and autonomy is compared with its resolved value, not the file's (an
// unchosen conservative resolves to sandbox), so Enter keeps such a file too.
func mergeSetupAnswers(file map[string]any, answers setupAnswers) error {
	cfg, _ := readConfig()
	if cfg == nil {
		cfg = &Config{} // the file parsed, so it is an existing config
	}
	eff := resolve(cfg, CLIOverrides{})
	effective := map[string]string{"client": eff.Client}
	var kv []string
	edit := func(key, answer string, always bool) {
		cur := findKeyDef(key).defaultVal // what the file means today
		if now, set := file[key]; set {
			cur = fmt.Sprint(now)
		} else if always {
			cur = effective[key]
		}
		if cur == answer {
			return
		}
		tomlVal := ""
		if answer != "" && (always || answer != findKeyDef(key).defaultVal) {
			tomlVal, _ = formatTOMLValue(findKeyDef(key), answer)
		}
		kv = append(kv, key, tomlVal)
	}
	edit("client", answers.Client, true)
	edit("mode", answers.Mode, false)
	if answers.Autonomy != "" && answers.Autonomy != eff.Autonomy { // "": not asked
		kv = append(kv, autonomyKV(tomlString(answers.Autonomy))...)
	}
	edit("model", answers.Model, false)
	edit("reasoning_effort", answers.ReasoningEffort, false)
	if answers.AutoUpdate != "" {
		edit("auto_update", answers.AutoUpdate, false)
	}
	if len(kv) == 0 {
		return nil
	}
	return updateConfigKeys(kv...)
}

// setupPreselect is the answer each wizard question starts on: the built-in
// defaults on a first run, and what the config holds on a rerun, so Enter on
// every question keeps each setting (#1022, #1348).
func setupPreselect(existing *Config) setupAnswers {
	a := setupAnswers{
		Client:     findKeyDef("client").defaultVal,
		Mode:       findKeyDef("mode").defaultVal,
		AutoUpdate: findKeyDef("auto_update").defaultVal,
		Autonomy:   resolve(existing, CLIOverrides{}).Autonomy,
	}
	if existing == nil {
		return a
	}
	a.Client = cfgClient(existing)
	if existing.Mode != nil {
		a.Mode = *existing.Mode
	}
	if existing.Model != nil {
		a.Model = *existing.Model
	}
	if existing.ReasoningEffort != nil {
		a.ReasoningEffort = *existing.ReasoningEffort
	}
	if existing.AutoUpdate != nil {
		a.AutoUpdate = fmt.Sprint(*existing.AutoUpdate)
	}
	return a
}

