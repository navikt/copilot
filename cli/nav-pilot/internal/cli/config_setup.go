var runConfigSetupFn = runConfigSetup

// runConfigSetup runs the interactive first-run wizard.
// Returns nil on user cancel (so callers never block).
// Each huh prompt: on cancel/error, print a soft notice and return nil.
//
// flagSource is the --source the command line carried, or "" when it carried
// none. It is the flag half of the source precedence, and the wizard needs it
// because first-run setup happens before the config file exists: a first run
// with a custom source has nowhere else to learn it from (#813).
func runConfigSetup(flagSource string) error { return runConfigSetupWith(flagSource, false) }

// runConfigSetupWith is runConfigSetup; advanced adds the network question.
func runConfigSetupWith(flagSource string, advanced bool) error {
	fmt.Println()
	fmt.Printf("%s  First-run setup\n", bold("🧭 nav-pilot"))
	fmt.Println(dim("  Set your preferences."))
	fmt.Println()
	maybeTelemetryNotice()

	existing, _ := readConfig()
	answers := setupPreselect(existing)
	opencodeLabel := clientLabel["opencode"] + " (default)"
	if existing != nil {
		opencodeLabel = clientLabel["opencode"]
	}

	err := huh.NewSelect[string]().
		Title("Which coding agent?").
		Options(
			huh.NewOption(opencodeLabel, "opencode"),
			huh.NewOption(clientLabel["copilot"], "copilot"),
			huh.NewOption(clientLabel["pi"], "pi"),
		).
		Value(&answers.Client).
		WithTheme(navTheme()).
		Run()
	if err != nil {
		return setupSkipped(err)
	}
	if answers.Client == "opencode" {
		if answers.Client, err = opencodeForSetup(); err != nil {
			return setupSkipped(err)
		}
	}

	err = huh.NewSelect[string]().
		Title("Conversation mode").
		Options(
			huh.NewOption("default", "default"),
			huh.NewOption("plan — think before acting", "plan"),
			huh.NewOption("autopilot: no confirmations, and the agent cannot ask you", "autopilot"),
		).
		Value(&answers.Mode).
		WithTheme(navTheme()).
		Run()
	if err != nil {
		return setupSkipped(err)
	}

	// How the agent runs commands, and what it may do with git. Each
	// question starts on what this machine has today, so Enter on a rerun
	// changes nothing.
	cpltPath, _ := findCplt()
	cur := cpltGitState{Preset: "standard"}
	if cpltPath != "" {
		cur = readCpltGitState(cpltPath)
	}
	if cur.Preset == "" {
		// cplt could not say, or has a preset this build does not know:
		// read it as cplt's default, and never write the preset over it.
		cur.Preset = "standard"
	}
	curChoice := autonomyChoice{Autonomy: answers.Autonomy, Preset: cur.Preset, Push: cur.effectivePush()}
	choice, err := askAutonomy(answers.Client, curChoice, advanced)
	if err != nil {
		return setupSkipped(err)
	}
	answers.Autonomy = choice.Autonomy

	// Model picker: providers with a curated model list get a select widget;
	// others (pi, unknown future providers) get a free-text input.
	p, _ := providerFor(answers.Client)
	modelDesc := "Pick a model, or leave it unset for the agentpakke's default (the agent's own if it names none)."
	if p != nil && p.DefaultModel() != "" {
		modelDesc = "Pick a model (provider/model format), or leave unset to use the Nav default."
	}
	model, err := promptModel(p, "Model", modelDesc, answers.Model)
	if err != nil {
		return setupSkipped(err)
	}
	answers.Model = model

	err = huh.NewSelect[string]().
		Title("Reasoning effort").
		Description("Controls how hard the model thinks. Leave unset to use the agent default.").
		Options(
			huh.NewOption("Unset (the agent's own default)", ""),
			huh.NewOption("none", "none"),
			huh.NewOption("low", "low"),
			huh.NewOption("medium", "medium"),
			huh.NewOption("high", "high"),
			huh.NewOption("xhigh", "xhigh"),
			huh.NewOption("max", "max"),
		).
		Value(&answers.ReasoningEffort).
		WithTheme(navTheme()).
		Run()
	if err != nil {
		return setupSkipped(err)
	}

	err = huh.NewSelect[string]().
		Title("Auto-update nav-pilot").
		Description("Automatically install new CLI versions in the background.").
		Options(
			huh.NewOption("Yes", "true"),
			huh.NewOption("No: say when a new version is out, and ask to upgrade once 7 days behind", "false"),
		).
		Value(&answers.AutoUpdate).
		WithTheme(navTheme()).
		Run()
	if err != nil {
		return setupSkipped(err)
	}

	// One screen of what changes; nothing is written without the yes.
	var changes []cpltChange
	allowlistPath, host, keptAllowlist := "", "", ""
	if cpltPath != "" {
		changes = cpltChanges(cur, choice)
		// Leaving strict does not drop the allowlist: cplt enforces it under
		// every preset, so the summary says it stays.
		if choice.Preset != cpltStrictPreset {
			keptAllowlist = cpltConfigGet(cpltPath, "proxy.allowed_domains")
		}
		// nav-pilot's own list from strict may go with it; the default is
		// to keep it, since it is the user's config.
		if drop := leavingStrictAllowlist(cur.Preset, choice.Preset, keptAllowlist); drop != nil {
			remove := false
			if err := huh.NewConfirm().
				Title("Remove the network allowlist nav-pilot set up for strict?").
				Description("Without it, cplt's standard rules decide which hosts are reachable. " + keptAllowlist + " stays on disk.").
				Value(&remove).
				WithTheme(navTheme()).
				Run(); err != nil {
				return setupSkipped(err)
			}
			if remove {
				changes = append(changes, *drop)
				keptAllowlist = ""
			}
		}
		for _, ch := range changes {
			if ch.Key != "sandbox.preset" || ch.To != cpltStrictPreset {
				continue
			}
			if ok, reason := strictPresetSupported(); !ok {
				return fmt.Errorf("nav-pilot will not set sandbox.preset = strict here: %s. Nothing was written", reason)
			}
			fmt.Println(dim("Checking the sandbox…"))
			allowlistPath, host = cpltAgentHostShutOut(cpltPath, cpltEnforcement())
		}
	}
	save := true
	if err := huh.NewConfirm().
		Title("Save these settings?").
		Description(autonomySummary(choice, changes, cpltPath != "", keptAllowlist)).
		Affirmative("Save").
		Negative("Cancel").
		Value(&save).
		WithTheme(navTheme()).
		Run(); err != nil {
		return setupSkipped(err)
	}
	if !save {
		fmt.Println(dim("  Nothing saved. Run 'nav-pilot config setup' anytime."))
		return nil
	}
	if err := applyCpltChanges(cpltPath, changes, allowlistPath, host); err != nil {
		return fmt.Errorf("saving cplt config: %w", err)
	}

	if err := writeSetupConfig(answers); err != nil {
		return fmt.Errorf("saving config: %w", err)
	}

	// Bootstrap the selected provider on first run (e.g. opencode: write OTel config
	// and seed Nav context so the user is immediately ready without a separate step).
	//
	// The --source this run carried, else the file the wizard just wrote
	// (writeSetupConfig preserves a persisted source), so a user with their own
	// pakke gets that pakke seeded rather than the built-in default (#813) —
	// the same precedence every other source lookup uses. A bad value is not
	// worth aborting setup over: the seeding is the optional part.
	if p != nil {
		seedSource, srcErr := sourceRepoFor(flagSource)
		if srcErr != nil {
			fmt.Fprintf(os.Stderr, "%s Could not read the configured source: %v\n", yellow("⚠"), srcErr)
		}
		if summary, ctxErr := p.Bootstrap(ResolvedConfig{Client: answers.Client, Source: seedSource}); ctxErr != nil {
			fmt.Fprintf(os.Stderr, "%s Could not seed Nav context for %s: %v\n", yellow("⚠"), p.DisplayName(), ctxErr)
		} else if summary != "" {
			fmt.Printf("  %s Nav context seeded: %s\n", green("✓"), summary)
		}
	}

	path := configPath()
	fmt.Printf("\n%s Saved %s\n", green("✓"), path)
	fmt.Println()
	fmt.Println("  Change settings anytime:")
	fmt.Printf("    %s\n", dim("nav-pilot config set <key> <value>"))
	fmt.Printf("    %s\n", dim("edit "+path+" directly"))
	fmt.Printf("    %s\n", dim("pass CLI flags per run (e.g. --client opencode)"))
	fmt.Println()

	// Setup checks stored host login only; a launch never probes.
	st, _ := ghAuthProbe()
	reportGHAuthBrief(os.Stdout, st, artifacts.FirstRun)
	if cpltPath != "" {
		offerCpltInit(cpltPath)
	}
	return nil
}

// opencodeForSetup settles a wizard answer of opencode on a machine without
// it: when the user says yes, nav-pilot installs opencode 2 with Homebrew, or
// without Homebrew with pnpm or npm. With none of them it installs nothing
// (opencode's own install script gives opencode 1 only) and says how to get
// opencode 2. Otherwise the wizard saves copilot and says how to switch later,
// naming both clients when neither is installed. It never saves a client that
// cannot start. Nothing is run without the yes.
// askInstallOpenCode is the one question a new install may get. Overridable
// in tests.
var askInstallOpenCode = func(cmd string) (bool, error) {
	install := true
	err := huh.NewConfirm().
		Title("opencode is not installed. Install it now?").
		Description("Runs " + cmd + ".").
		Affirmative("Install").
		Negative("Use GitHub Copilot instead").
		Value(&install).
		WithTheme(navTheme()).
		Run()
	return install, err
}

func opencodeForSetup() (string, error) {
	if opencodeInstalled() {
		return "opencode", nil
	}
	cmd := opencodeInstallCommand()
	if cmd != "" {
		install, err := askInstallOpenCode(cmd)
		if errors.Is(err, huh.ErrUserAborted) {
			return "", err
		} else if err != nil {
			install = false // a prompt that could not run is no answer
		}
		if install {
			if err := installOpenCode(cmd); err != nil {
				fmt.Fprintf(os.Stderr, "%s %s: %v\n", yellow("⚠"), cmd, err)
			} else {
				fmt.Printf("  %s opencode installed\n", green("✓"))
				return "opencode", nil
			}
		}
	}
	if !opencodePlatform() {
		fmt.Printf("  %s, so nav-pilot will use GitHub Copilot.\n", opencodeOffPlatform)
		return "copilot", nil
	}
	// steps is how to get opencode 2 and switch to it.
	steps := cmd + ", then " + bold("nav-pilot config set client opencode")
	if cmd == "" {
		steps = "install " + opencodeNeeds + ", run " + opencodeCommands() + ", then " + bold("nav-pilot config set client opencode")
	}
	if p, err := providerFor("copilot"); err == nil && !p.Available() {
		fmt.Printf("  Neither opencode nor GitHub Copilot is installed. nav-pilot saves GitHub Copilot for now. Install one of them:\n    opencode: %s\n    GitHub Copilot CLI: %s\n",
			steps, providerpkg.CopilotInstallCommand)
		return "copilot", nil
	}
	fmt.Printf("  opencode is not installed, so nav-pilot will use GitHub Copilot. To switch later: %s\n", steps)
	return "copilot", nil
}

// installOpenCode runs cmd, one of opencodeInstallCommand's package-manager
// commands (fixed strings, no shell), and checks that opencode is then on PATH.
func installOpenCode(cmd string) error {
	args := strings.Fields(cmd)
	c := exec.Command(args[0], args[1:]...)
	c.Stdout, c.Stderr = os.Stdout, os.Stderr
	if err := c.Run(); err != nil {
		return err
	}
	if !opencodeInstalled() {
		return errors.New("opencode is still not on PATH")
	}
	return nil
}

// opencodeBrewFormula is opencode 2 from opencode's tap, the formula
// OpenCode2InstallHint names; anomalyco/tap/opencode is still opencode 1.
const opencodeBrewFormula = "anomalyco/tap/opencode-v2"

// opencodeBrewInstall installs opencode 2 through Homebrew.
const opencodeBrewInstall = "brew install " + opencodeBrewFormula

// opencodeNpmInstall installs opencode 2 through npm. opencode 2 is not
// published as opencode-ai, which is opencode 1.
const opencodeNpmInstall = "npm i -g @opencode/cli@" + providerpkg.OpenCode2InstallVersion

// opencodeNeeds is what a machine with no installer gets first. opencode's own
// install script is not offered: it installs opencode 1 only, and no new user
// should start on opencode 1.
const opencodeNeeds = "Homebrew (https://brew.sh) or Node.js (https://nodejs.org)"

// opencodeCommands names both opencode 2 installs, for after opencodeNeeds.
func opencodeCommands() string {
	return bold(opencodeBrewInstall) + " or " + bold(opencodeNpmInstall)
}

// installGOOS is runtime.GOOS; tests set it.
var installGOOS = runtime.GOOS

// opencodePlatform reports whether opencode 2 runs here (under cplt).
func opencodePlatform() bool { return installGOOS == "darwin" || installGOOS == "linux" }

// opencodeOffPlatform starts the message for a platform opencode 2 skips.
const opencodeOffPlatform = "opencode 2 runs only on macOS and Linux"

// opencodeInstallCommand is how this machine gets opencode 2: Homebrew, else
// pnpm or npm, pinned so it cannot install an untested major. It is "" with
// none of them, and on a platform other than macOS and Linux, where opencode 2
// does not run under cplt.
func opencodeInstallCommand() string {
	if !opencodePlatform() {
		return ""
	}
	if _, err := exec.LookPath("brew"); err == nil {
		return opencodeBrewInstall
	}
	if _, err := exec.LookPath("pnpm"); err == nil {
		// Corepack can provide pnpm before its global bin directory is set up.
		home := os.Getenv("PNPM_HOME")
		if info, err := os.Stat(home); err == nil && info.IsDir() && filepath.IsAbs(home) {
			for _, dir := range filepath.SplitList(os.Getenv("PATH")) {
				if filepath.Clean(dir) == filepath.Clean(home) {
					return "pnpm add -g @opencode/cli@" + providerpkg.OpenCode2InstallVersion
				}
			}
		}
	}
	if _, err := exec.LookPath("npm"); err == nil {
		return opencodeNpmInstall
	}
	return ""
}

// setupSkipped is how the wizard ends when a prompt returns err. Ctrl-C ends
// the whole run, and the wizard has written nothing yet. Any other error is a
// prompt that could not run: the wizard steps aside with one line and the run
// goes on without a config.
func setupSkipped(err error) error {
	if errors.Is(err, huh.ErrUserAborted) {
		return cancelledError{nothingWritten: true}
	}
	fmt.Println(dim("  Setup skipped — run 'nav-pilot config setup' anytime."))
	return nil
}

// maybeRunFirstRunSetup writes a new install's config on the first
// interactive run, asking nothing unless no client is installed.
// It is a no-op when any of the following are true:
//   - the terminal is not interactive (isInteractive() == false)
//   - the config file already exists
func maybeRunFirstRunSetup(flagSource string) error {
	firstRunWrote = false
	if !isInteractive() {
		return nil
	}
	if _, err := os.Stat(configPath()); !errors.Is(err, os.ErrNotExist) {
		// File exists (err == nil) or some other stat error — skip setup.
		return nil
	}
	// The install that follows adds the source's hooks, so the wizard's
	// context seeding must not first tell the user to run nav-pilot install
	// for them (#1962 F9).
	artifacts.FirstRun = true
	defer func() { artifacts.FirstRun = false }()
	wizardShown = true
	if err := firstRunFn(flagSource); err != nil {
		return err
	}
	firstRunWrote = startedFresh
	return nil
}

